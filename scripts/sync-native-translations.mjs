import { mkdirSync, readFileSync, writeFileSync } from "node:fs";

const locales = ["en", "es", "it", "hr", "pt"];
const catalogs = locales.map(locale => JSON.parse(readFileSync(`src/locales/${locale}.json`, "utf8")));
const nativeKeys = [
  "Hecate journey", "Open Hecate to start or stop a journey.", "Open Hecate to refresh",
  "Exploring", "Exploring…", "Journey complete", "Stop journey", "Open Hecate to stop journey",
  "this walk", "walked", "new area", "time", "Arrived", "Now", "In {{value0}}",
];
const androidKeys = {
  journey_channel: "Walking journeys",
  journey_channel_description: "Live walking distance, new area, elapsed time, and journey controls",
  journey_exploring: "Exploring…",
  journey_complete: "Journey complete",
  journey_stop: "Stop journey",
  journey_walk: "this walk",
  journey_walked: "walked",
  journey_new_area: "new area",
};

for (const [index, catalog] of catalogs.entries()) {
  for (const key of [...nativeKeys, ...Object.values(androidKeys)]) {
    if (typeof catalog[key] !== "string") throw new Error(`Missing ${locales[index]} native translation: ${key}`);
  }
}

const swiftLanguages = locales.map((locale, index) => {
  const entries = nativeKeys.map(key => `            ${JSON.stringify(key)}: ${JSON.stringify(catalogs[index][key])}`);
  return `        ${JSON.stringify(locale)}: [\n${entries.join(",\n")}\n        ]`;
}).join(",\n");
const swift = `
/// Shared localized copy generated by scripts/sync-native-translations.mjs. Edit src/locales instead.
enum JourneyLocalization {
    static let languages = ["en", "es", "it", "hr", "pt"]
    static let translations: [String: [String: String]] = [
${swiftLanguages}
    ]
    static var deviceLanguage: String { Locale.preferredLanguages.compactMap { value in languages.first { $0 == value.lowercased().split(separator: "-").first.map(String.init) } }.first ?? "en" }
    static func text(_ key: String, language: String?) -> String {
        let resolved = language ?? deviceLanguage
        guard let value = translations[resolved]?[key] else { preconditionFailure("Missing journey translation: \\(resolved), \\(key)") }
        return value
    }
}
`;
const sharedFile = "ios/App/Shared/JourneyActivityAttributes.swift";
const sharedSource = readFileSync(sharedFile, "utf8");
const markerIndex = sharedSource.indexOf("\n/// Shared localized copy");
if (markerIndex < 0) throw new Error("Missing generated journey localization marker.");
writeFileSync(sharedFile, sharedSource.slice(0, markerIndex) + swift);

function escapeAndroidString(value) {
  return value.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/'/g, "\\'");
}

for (const [index, locale] of locales.entries()) {
  const directory = `android/app/src/main/res/values${locale === "en" ? "" : `-${locale}`}`;
  const entries = Object.entries(androidKeys).map(([key, text]) =>
    `    <string name="${key}">${escapeAndroidString(catalogs[index][text])}</string>`,
  );
  mkdirSync(directory, { recursive: true });
  writeFileSync(`${directory}/journey_strings.xml`, `<?xml version="1.0" encoding="utf-8"?>\n<resources>\n${entries.join("\n")}\n</resources>\n`);
}
